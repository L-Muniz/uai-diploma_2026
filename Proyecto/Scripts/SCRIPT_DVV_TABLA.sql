-- Un DVV por tabla (no por usuario). Limpia filas viejas y deja una sola de USUARIO.
CREATE OR ALTER PROCEDURE DVV_BUSCAR_X_TIPO
    @tipoEntidad VARCHAR(50)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT TOP 1 [ID_DVV], [ID_ENTIDAD], [TIPO_ENTIDAD], [DV_USERNAME], [DV_PASSWORD], [DV_BLOQUEADO], [FECHA_CREACION]
    FROM [DIGITO_VERIFICADOR_VERTICAL]
    WHERE [TIPO_ENTIDAD] = @tipoEntidad
    ORDER BY CASE WHEN [ID_ENTIDAD] IS NULL OR [ID_ENTIDAD] = 0 THEN 0 ELSE 1 END, [ID_DVV] DESC;
END
GO

CREATE OR ALTER PROCEDURE DVV_EDITAR
    @id INT,
    @dvUsername INT,
    @dvPassword INT,
    @dvBloqueado INT
AS
BEGIN
    UPDATE [DIGITO_VERIFICADOR_VERTICAL]
    SET [DV_USERNAME] = @dvUsername,
        [DV_PASSWORD] = @dvPassword,
        [DV_BLOQUEADO] = @dvBloqueado,
        [ID_ENTIDAD] = 0,
        [FECHA_CREACION] = GETDATE()
    WHERE [ID_DVV] = @id;
END
GO

DELETE d
FROM [DIGITO_VERIFICADOR_VERTICAL] d
WHERE d.[TIPO_ENTIDAD] = 'USUARIO'
  AND d.[ID_DVV] < (
        SELECT MAX(x.[ID_DVV])
        FROM [DIGITO_VERIFICADOR_VERTICAL] x
        WHERE x.[TIPO_ENTIDAD] = 'USUARIO'
      );

UPDATE [DIGITO_VERIFICADOR_VERTICAL]
SET [ID_ENTIDAD] = 0
WHERE [TIPO_ENTIDAD] = 'USUARIO';
GO
