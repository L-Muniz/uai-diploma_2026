FROM (VALUES
    ('CIUDADANO', 'PROC_SUSCRIBIRSE_MATERIALES'), ('CIUDADANO', 'PROC_VER_ESTADISTICAS_VENTAS'),
    ('USUARIO', 'PROC_SUSCRIBIRSE_MATERIALES'), ('USUARIO', 'PROC_VER_ESTADISTICAS_VENTAS')
) AS X (ROL, CODIGO)
JOIN dbo.ROL R ON R.NOMBRE = X.ROL
JOIN dbo.PERMISO P ON P.CODIGO = X.CODIGO
WHERE NOT EXISTS (SELECT 1 FROM dbo.ROL_PERMISO RP WHERE RP.ID_ROL = R.ID_ROL AND RP.ID_PERMISO = P.ID_PERMISO);
GO

-- ---------- perfil del usuario ----------

CREATE OR ALTER PROCEDURE dbo.DATOS_USUARIO_OBTENER @ID_USUARIO INT AS
    SELECT ID_USUARIO, FECHA_NACIMIENTO, LATITUD, LONGITUD, LOCALIDAD
    FROM dbo.DATOS_USUARIO WHERE ID_USUARIO = @ID_USUARIO;
GO

CREATE OR ALTER PROCEDURE dbo.DATOS_USUARIO_GUARDAR
    @ID_USUARIO INT, @FECHA_NACIMIENTO DATE, @LATITUD DECIMAL(9,6), @LONGITUD DECIMAL(9,6), @LOCALIDAD NVARCHAR(100) AS
BEGIN TRY
    BEGIN TRANSACTION;
    IF EXISTS (SELECT 1 FROM dbo.DATOS_USUARIO WHERE ID_USUARIO = @ID_USUARIO)
        UPDATE dbo.DATOS_USUARIO
        SET FECHA_NACIMIENTO = @FECHA_NACIMIENTO, LATITUD = @LATITUD, LONGITUD = @LONGITUD, LOCALIDAD = @LOCALIDAD
        WHERE ID_USUARIO = @ID_USUARIO;
    ELSE
        INSERT INTO dbo.DATOS_USUARIO (ID_USUARIO, FECHA_NACIMIENTO, LATITUD, LONGITUD, LOCALIDAD)
        VALUES (@ID_USUARIO, @FECHA_NACIMIENTO, @LATITUD, @LONGITUD, @LOCALIDAD);
    COMMIT;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
END CATCH
GO

-- ---------- suscripciones a materiales ----------

CREATE OR ALTER PROCEDURE dbo.SUSCRIPCIONES_LISTAR @ID_USUARIO INT AS
    SELECT M.ID_MATERIAL AS ID, M.NOMBRE AS Material,
           CASE WHEN S.ID_USUARIO IS NULL THEN 0 ELSE 1 END AS Suscripto
    FROM dbo.MATERIAL M
    LEFT JOIN dbo.SUSCRIPCION_MATERIAL S ON S.ID_MATERIAL = M.ID_MATERIAL AND S.ID_USUARIO = @ID_USUARIO
    ORDER BY M.NOMBRE;
GO

-- @MATERIALES: lista de IDs separada por comas. Reemplaza las suscripciones del usuario.
CREATE OR ALTER PROCEDURE dbo.SUSCRIPCIONES_GUARDAR @ID_USUARIO INT, @MATERIALES NVARCHAR(MAX) AS
BEGIN TRY
    BEGIN TRANSACTION;
    DELETE FROM dbo.SUSCRIPCION_MATERIAL WHERE ID_USUARIO = @ID_USUARIO;
    INSERT INTO dbo.SUSCRIPCION_MATERIAL (ID_USUARIO, ID_MATERIAL)
    SELECT DISTINCT @ID_USUARIO, TRY_CONVERT(INT, LTRIM(RTRIM(value)))
    FROM STRING_SPLIT(ISNULL(@MATERIALES, N''), N',')
    WHERE TRY_CONVERT(INT, LTRIM(RTRIM(value))) IS NOT NULL;
    COMMIT;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
END CATCH
GO

-- Guías de reutilización de los materiales que sigue el usuario (contenido personalizado).
CREATE OR ALTER PROCEDURE dbo.GUIAS_SUSCRIPTAS_LISTAR @ID_USUARIO INT AS
    SELECT G.ID_GUIA AS ID, M.NOMBRE AS Material, G.TITULO AS Titulo, G.PASOS AS Pasos, G.DIFICULTAD AS Dificultad
    FROM dbo.GUIA_REUTILIZACION G
    JOIN dbo.MATERIAL M ON M.ID_MATERIAL = G.ID_MATERIAL
    JOIN dbo.SUSCRIPCION_MATERIAL S ON S.ID_MATERIAL = G.ID_MATERIAL AND S.ID_USUARIO = @ID_USUARIO
    ORDER BY M.NOMBRE, G.TITULO;
GO

-- ---------- estadísticas de ventas del vendedor (período [@DESDE, @HASTA]) ----------

CREATE OR ALTER PROCEDURE dbo.VENDEDOR_ESTADISTICAS_RESUMEN @ID_VENDEDOR INT, @DESDE DATE, @HASTA DATE AS
    SELECT COUNT(O.ID_ORDEN) AS Ventas,
           ISNULL(SUM(O.MONTO_BRUTO), 0) AS MontoBruto,
           ISNULL(SUM(CASE WHEN L.ESTADO = N'PAGADA' THEN L.MONTO_NETO ELSE 0 END), 0) AS NetoLiquidado,
           ISNULL(SUM(CASE WHEN L.ESTADO IN (N'RETENIDA', N'DISPONIBLE', N'CONGELADA') THEN L.MONTO_NETO ELSE 0 END), 0) AS NetoPendiente,
           ISNULL((SELECT SUM(C.MONTO) FROM dbo.COMISION C JOIN dbo.ORDEN_VENTA O2 ON O2.ID_ORDEN = C.ID_ORDEN
                   WHERE O2.ID_VENDEDOR = @ID_VENDEDOR AND CAST(O2.FECHA AS DATE) BETWEEN @DESDE AND @HASTA), 0) AS Comisiones
    FROM dbo.ORDEN_VENTA O
    LEFT JOIN dbo.LIQUIDACION_VENDEDOR L ON L.ID_ORDEN = O.ID_ORDEN
    WHERE O.ID_VENDEDOR = @ID_VENDEDOR AND CAST(O.FECHA AS DATE) BETWEEN @DESDE AND @HASTA
      AND O.ESTADO <> N'DEVUELTA';
GO

CREATE OR ALTER PROCEDURE dbo.VENDEDOR_ESTADISTICAS_PRODUCTOS @ID_VENDEDOR INT, @DESDE DATE, @HASTA DATE AS
    SELECT P.NOMBRE AS Producto, SUM(D.CANTIDAD) AS Unidades, SUM(D.CANTIDAD * D.PRECIO_UNITARIO) AS MontoBruto
    FROM dbo.ORDEN_DETALLE D
    JOIN dbo.ORDEN_VENTA O ON O.ID_ORDEN = D.ID_ORDEN
    JOIN dbo.PRODUCTO P ON P.ID_PRODUCTO = D.ID_PRODUCTO
    WHERE O.ID_VENDEDOR = @ID_VENDEDOR AND CAST(O.FECHA AS DATE) BETWEEN @DESDE AND @HASTA
      AND O.ESTADO <> N'DEVUELTA'
    GROUP BY P.NOMBRE
    ORDER BY MontoBruto DESC;
GO
