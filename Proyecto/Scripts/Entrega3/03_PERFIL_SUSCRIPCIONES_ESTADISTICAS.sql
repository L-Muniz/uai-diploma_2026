    ID_USUARIO INT NOT NULL PRIMARY KEY REFERENCES dbo.USUARIO(ID_USUARIO),
    FECHA_NACIMIENTO DATE NULL,
    LATITUD DECIMAL(9,6) NULL,
    LONGITUD DECIMAL(9,6) NULL,
    LOCALIDAD NVARCHAR(100) NULL
);
GO

IF OBJECT_ID('dbo.SUSCRIPCION_MATERIAL', 'U') IS NULL
CREATE TABLE dbo.SUSCRIPCION_MATERIAL (
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    ID_MATERIAL INT NOT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    FECHA_ALTA DATETIME NOT NULL DEFAULT GETDATE(),
    PRIMARY KEY (ID_USUARIO, ID_MATERIAL)
);
GO

