-- Acredita puntos (negativos para descontar) y devuelve el saldo resultante. Crea la cuenta si no existe.
CREATE OR ALTER PROCEDURE dbo.CUENTA_ACREDITAR @ID_USUARIO INT, @PUNTOS INT, @TIPO NVARCHAR(20), @MOTIVO NVARCHAR(200) AS
BEGIN TRY
    BEGIN TRANSACTION;
    IF NOT EXISTS (SELECT 1 FROM dbo.CUENTA_ECOPUNTOS WHERE ID_USUARIO = @ID_USUARIO)
        INSERT INTO dbo.CUENTA_ECOPUNTOS (ID_USUARIO) VALUES (@ID_USUARIO);
    DECLARE @ID_CUENTA INT = (SELECT ID_CUENTA FROM dbo.CUENTA_ECOPUNTOS WHERE ID_USUARIO = @ID_USUARIO);
    INSERT INTO dbo.MOVIMIENTO_ECOPUNTOS (ID_CUENTA, TIPO, PUNTOS, MOTIVO) VALUES (@ID_CUENTA, @TIPO, @PUNTOS, @MOTIVO);
    UPDATE dbo.CUENTA_ECOPUNTOS SET SALDO = SALDO + @PUNTOS WHERE ID_CUENTA = @ID_CUENTA;
    COMMIT;
    SELECT SALDO FROM dbo.CUENTA_ECOPUNTOS WHERE ID_CUENTA = @ID_CUENTA;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
END CATCH
GO

