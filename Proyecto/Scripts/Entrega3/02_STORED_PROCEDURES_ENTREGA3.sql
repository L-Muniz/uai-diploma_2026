-- Resuelve el reclamo. Procedente: devuelve la orden, restituye el stock y cancela la liquidación.
-- Improcedente: libera la orden y vuelve la liquidación a retenida.
CREATE OR ALTER PROCEDURE dbo.RECLAMO_RESOLVER @ID_RECLAMO INT, @PROCEDENTE BIT AS
BEGIN TRY
    BEGIN TRANSACTION;
    DECLARE @ID_ORDEN INT = (SELECT ID_ORDEN FROM dbo.RECLAMO WHERE ID_RECLAMO = @ID_RECLAMO AND ESTADO = N'ABIERTO');
    IF @ID_ORDEN IS NULL THROW 50031, N'El reclamo no está abierto.', 1;
    IF @PROCEDENTE = 1
    BEGIN
        UPDATE dbo.RECLAMO SET ESTADO = N'PROCEDENTE' WHERE ID_RECLAMO = @ID_RECLAMO;
        UPDATE P SET P.STOCK = P.STOCK + D.CANTIDAD
        FROM dbo.PRODUCTO P JOIN dbo.ORDEN_DETALLE D ON D.ID_PRODUCTO = P.ID_PRODUCTO
        WHERE D.ID_ORDEN = @ID_ORDEN;
        UPDATE dbo.ORDEN_VENTA SET ESTADO = N'DEVUELTA' WHERE ID_ORDEN = @ID_ORDEN;
        UPDATE dbo.LIQUIDACION_VENDEDOR SET ESTADO = N'CANCELADA' WHERE ID_ORDEN = @ID_ORDEN AND ESTADO = N'CONGELADA';
    END
    ELSE
    BEGIN
        UPDATE dbo.RECLAMO SET ESTADO = N'IMPROCEDENTE' WHERE ID_RECLAMO = @ID_RECLAMO;
        UPDATE dbo.ORDEN_VENTA SET ESTADO = N'DESPACHADA' WHERE ID_ORDEN = @ID_ORDEN;
        UPDATE dbo.LIQUIDACION_VENDEDOR SET ESTADO = N'RETENIDA' WHERE ID_ORDEN = @ID_ORDEN AND ESTADO = N'CONGELADA';
    END
    COMMIT;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
END CATCH
GO
