-- Registra la orden ya cobrada (stock, orden, detalle, pago, comisión y liquidación retenida). Devuelve el ID de la orden.
CREATE OR ALTER PROCEDURE dbo.VENTA_REGISTRAR
    @ID_PRODUCTO INT, @CANTIDAD INT, @PRECIO DECIMAL(10,2), @MONTO DECIMAL(10,2), @ID_COMPRADOR INT,
    @ID_VENDEDOR INT, @DIRECCION NVARCHAR(200), @REFERENCIA NVARCHAR(100), @PORCENTAJE DECIMAL(5,2),
    @COMISION DECIMAL(10,2), @NETO DECIMAL(10,2) AS
BEGIN TRY
    BEGIN TRANSACTION;
    UPDATE dbo.PRODUCTO SET STOCK = STOCK - @CANTIDAD WHERE ID_PRODUCTO = @ID_PRODUCTO AND STOCK >= @CANTIDAD;
    IF @@ROWCOUNT = 0 THROW 50010, N'Stock insuficiente para completar la compra.', 1;
    DECLARE @ID_ORDEN INT;
    INSERT INTO dbo.ORDEN_VENTA (ID_COMPRADOR, ID_VENDEDOR, ESTADO, MONTO_BRUTO, DIRECCION_ENVIO)
    VALUES (@ID_COMPRADOR, @ID_VENDEDOR, N'PAGADA_PENDIENTE_DESPACHO', @MONTO, @DIRECCION);
    SET @ID_ORDEN = SCOPE_IDENTITY();
    INSERT INTO dbo.ORDEN_DETALLE (ID_ORDEN, ID_PRODUCTO, CANTIDAD, PRECIO_UNITARIO) VALUES (@ID_ORDEN, @ID_PRODUCTO, @CANTIDAD, @PRECIO);
    INSERT INTO dbo.PAGO (ID_ORDEN, REFERENCIA_PASARELA, MONTO, ESTADO) VALUES (@ID_ORDEN, @REFERENCIA, @MONTO, N'APROBADO');
    INSERT INTO dbo.COMISION (ID_ORDEN, PORCENTAJE, MONTO) VALUES (@ID_ORDEN, @PORCENTAJE, @COMISION);
    INSERT INTO dbo.LIQUIDACION_VENDEDOR (ID_ORDEN, MONTO_NETO, ESTADO) VALUES (@ID_ORDEN, @NETO, N'RETENIDA');
    COMMIT;
    SELECT @ID_ORDEN;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
END CATCH
GO

