CREATE OR ALTER PROCEDURE dbo.INDICADOR_ACOPIO_POR_MATERIAL @PERIODO NVARCHAR(7) AS
    SELECT M.NOMBRE AS Material, SUM(A.PESO_KG) AS Kg
    FROM dbo.ACOPIO A JOIN dbo.MATERIAL M ON M.ID_MATERIAL = A.ID_MATERIAL
    WHERE CONVERT(CHAR(7), A.FECHA_RECEPCION, 126) = @PERIODO
    GROUP BY M.NOMBRE ORDER BY M.NOMBRE;
GO

CREATE OR ALTER PROCEDURE dbo.INDICADOR_VENTAS @PERIODO NVARCHAR(7) AS
    SELECT COUNT(*) AS Ordenes, ISNULL(SUM(O.MONTO_BRUTO), 0) AS MontoBruto,
           ISNULL((SELECT SUM(C.MONTO) FROM dbo.COMISION C WHERE CONVERT(CHAR(7), C.FECHA, 126) = @PERIODO), 0) AS Comisiones
    FROM dbo.ORDEN_VENTA O WHERE CONVERT(CHAR(7), O.FECHA, 126) = @PERIODO;
GO

CREATE OR ALTER PROCEDURE dbo.INDICADOR_COSTO_CANJES @PERIODO NVARCHAR(7) AS
    SELECT ISNULL(SUM(B.COSTO_EMPRESA), 0)
    FROM dbo.CANJE C JOIN dbo.BENEFICIO B ON B.ID_BENEFICIO = C.ID_BENEFICIO
    WHERE CONVERT(CHAR(7), C.FECHA, 126) = @PERIODO;
