-- @MATERIALES: lista de IDs separada por comas (se valida con TRY_CONVERT).
CREATE OR ALTER PROCEDURE dbo.PUNTO_VERDE_MATERIALES_GUARDAR @ID_PUNTO_VERDE INT, @MATERIALES NVARCHAR(MAX) AS
BEGIN TRY
    BEGIN TRANSACTION;
    DELETE FROM dbo.PUNTO_VERDE_MATERIAL WHERE ID_PUNTO_VERDE = @ID_PUNTO_VERDE;
    INSERT INTO dbo.PUNTO_VERDE_MATERIAL (ID_PUNTO_VERDE, ID_MATERIAL, ACEPTADO)
    SELECT DISTINCT @ID_PUNTO_VERDE, TRY_CONVERT(INT, LTRIM(RTRIM(value))), 1
    FROM STRING_SPLIT(ISNULL(@MATERIALES, N''), N',')
    WHERE TRY_CONVERT(INT, LTRIM(RTRIM(value))) IS NOT NULL;
    COMMIT;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
END CATCH
GO

