-- Abre el reclamo, marca la orden en reclamo y congela la liquidación. Devuelve el ID del reclamo.
CREATE OR ALTER PROCEDURE dbo.RECLAMO_REGISTRAR @ID_ORDEN INT, @ID_USUARIO INT, @MOTIVO NVARCHAR(300) AS
BEGIN TRY
    BEGIN TRANSACTION;
    UPDATE dbo.ORDEN_VENTA SET ESTADO = N'EN_RECLAMO'
    WHERE ID_ORDEN = @ID_ORDEN AND ID_COMPRADOR = @ID_USUARIO AND ESTADO = N'DESPACHADA';
    IF @@ROWCOUNT = 0 THROW 50030, N'Solo puede reclamar órdenes despachadas propias.', 1;
    DECLARE @ID_RECLAMO INT;
    INSERT INTO dbo.RECLAMO (ID_ORDEN, ID_USUARIO, MOTIVO) VALUES (@ID_ORDEN, @ID_USUARIO, @MOTIVO);
    SET @ID_RECLAMO = SCOPE_IDENTITY();
    UPDATE dbo.LIQUIDACION_VENDEDOR SET ESTADO = N'CONGELADA' WHERE ID_ORDEN = @ID_ORDEN AND ESTADO IN (N'RETENIDA', N'DISPONIBLE');
    COMMIT;
    SELECT @ID_RECLAMO;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
END CATCH
GO

