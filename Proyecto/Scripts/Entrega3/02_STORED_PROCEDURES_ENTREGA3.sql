-- Canje transaccional: valida beneficio y saldo, registra el canje y descuenta los puntos. Devuelve el ID del canje.
CREATE OR ALTER PROCEDURE dbo.CANJE_REGISTRAR @ID_USUARIO INT, @ID_BENEFICIO INT AS
BEGIN TRY
    BEGIN TRANSACTION;
    DECLARE @PUNTOS INT = (SELECT PUNTOS_REQUERIDOS FROM dbo.BENEFICIO WHERE ID_BENEFICIO = @ID_BENEFICIO AND ACTIVO = 1);
    IF @PUNTOS IS NULL THROW 50002, N'El beneficio no está disponible.', 1;
    IF NOT EXISTS (SELECT 1 FROM dbo.CUENTA_ECOPUNTOS WHERE ID_USUARIO = @ID_USUARIO)
        THROW 50003, N'El usuario no tiene cuenta de Eco-Puntos.', 1;
    DECLARE @ID_CUENTA INT = (SELECT ID_CUENTA FROM dbo.CUENTA_ECOPUNTOS WHERE ID_USUARIO = @ID_USUARIO);
    IF (SELECT SALDO FROM dbo.CUENTA_ECOPUNTOS WHERE ID_CUENTA = @ID_CUENTA) < @PUNTOS
        THROW 50004, N'Saldo insuficiente de Eco-Puntos.', 1;
    DECLARE @ID_CANJE INT;
    INSERT INTO dbo.CANJE (ID_USUARIO, ID_CUENTA, ID_BENEFICIO, PUNTOS_USADOS)
    VALUES (@ID_USUARIO, @ID_CUENTA, @ID_BENEFICIO, @PUNTOS);
    SET @ID_CANJE = SCOPE_IDENTITY();
    INSERT INTO dbo.MOVIMIENTO_ECOPUNTOS (ID_CUENTA, TIPO, PUNTOS, MOTIVO)
    VALUES (@ID_CUENTA, N'CANJE', -@PUNTOS, N'Canje de beneficio');
    UPDATE dbo.CUENTA_ECOPUNTOS SET SALDO = SALDO - @PUNTOS WHERE ID_CUENTA = @ID_CUENTA;
    COMMIT;
    SELECT @ID_CANJE;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK;
    THROW;
END CATCH
GO

