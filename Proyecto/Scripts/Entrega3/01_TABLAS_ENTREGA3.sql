-- ---------- N03: reconocimiento por reciclaje y canje ----------

IF OBJECT_ID('dbo.MATERIAL', 'U') IS NULL
CREATE TABLE dbo.MATERIAL (
    ID_MATERIAL INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE NVARCHAR(100) NOT NULL UNIQUE,
    CATEGORIA NVARCHAR(50) NOT NULL,
    UNIDAD_MEDIDA NVARCHAR(10) NOT NULL DEFAULT N'kg'
);
GO

IF OBJECT_ID('dbo.PUNTO_VERDE', 'U') IS NULL
CREATE TABLE dbo.PUNTO_VERDE (
    ID_PUNTO_VERDE INT IDENTITY(1,1) PRIMARY KEY,
    NOMBRE NVARCHAR(100) NOT NULL,
    DIRECCION NVARCHAR(200) NOT NULL,
    LATITUD DECIMAL(9,6) NULL,
    LONGITUD DECIMAL(9,6) NULL,
    HORARIO NVARCHAR(100) NULL,
    ACTIVO BIT NOT NULL DEFAULT 1
);
GO

IF OBJECT_ID('dbo.PUNTO_VERDE_MATERIAL', 'U') IS NULL
CREATE TABLE dbo.PUNTO_VERDE_MATERIAL (
    ID_PUNTO_VERDE INT NOT NULL REFERENCES dbo.PUNTO_VERDE(ID_PUNTO_VERDE),
    ID_MATERIAL INT NOT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    ACEPTADO BIT NOT NULL DEFAULT 1,
    PRIMARY KEY (ID_PUNTO_VERDE, ID_MATERIAL)
);
GO

IF OBJECT_ID('dbo.GUIA_REUTILIZACION', 'U') IS NULL
CREATE TABLE dbo.GUIA_REUTILIZACION (
    ID_GUIA INT IDENTITY(1,1) PRIMARY KEY,
    ID_MATERIAL INT NOT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    TITULO NVARCHAR(150) NOT NULL,
    PASOS NVARCHAR(MAX) NOT NULL,
    DIFICULTAD NVARCHAR(20) NOT NULL DEFAULT N'Baja'
);
GO

IF OBJECT_ID('dbo.DECLARACION_MATERIAL', 'U') IS NULL
CREATE TABLE dbo.DECLARACION_MATERIAL (
    ID_DECLARACION INT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    ID_MATERIAL INT NOT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    CANTIDAD DECIMAL(10,2) NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    ESTADO NVARCHAR(30) NOT NULL DEFAULT N'PENDIENTE'
);
GO

IF OBJECT_ID('dbo.RECOMENDACION', 'U') IS NULL
CREATE TABLE dbo.RECOMENDACION (
    ID_RECOMENDACION INT IDENTITY(1,1) PRIMARY KEY,
    ID_DECLARACION INT NOT NULL UNIQUE REFERENCES dbo.DECLARACION_MATERIAL(ID_DECLARACION),
    ID_GUIA INT NULL REFERENCES dbo.GUIA_REUTILIZACION(ID_GUIA),
    ID_PUNTO_VERDE INT NULL REFERENCES dbo.PUNTO_VERDE(ID_PUNTO_VERDE),
    TIPO_OPCION_ELEGIDA NVARCHAR(20) NULL,
    FECHA_GENERACION DATETIME NOT NULL DEFAULT GETDATE()
);
GO

IF OBJECT_ID('dbo.ACOPIO', 'U') IS NULL
CREATE TABLE dbo.ACOPIO (
    ID_ACOPIO INT IDENTITY(1,1) PRIMARY KEY,
    ID_DECLARACION INT NULL REFERENCES dbo.DECLARACION_MATERIAL(ID_DECLARACION),
    ID_PUNTO_VERDE INT NOT NULL REFERENCES dbo.PUNTO_VERDE(ID_PUNTO_VERDE),
    ID_MATERIAL INT NOT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    PESO_KG DECIMAL(10,2) NOT NULL,
    FECHA_RECEPCION DATETIME NOT NULL DEFAULT GETDATE(),
    ESTADO NVARCHAR(20) NOT NULL DEFAULT N'REGISTRADO'
);
GO

IF OBJECT_ID('dbo.CUENTA_ECOPUNTOS', 'U') IS NULL
CREATE TABLE dbo.CUENTA_ECOPUNTOS (
    ID_CUENTA INT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO INT NOT NULL UNIQUE REFERENCES dbo.USUARIO(ID_USUARIO),
    SALDO INT NOT NULL DEFAULT 0,
    NIVEL INT NOT NULL DEFAULT 1
);
GO

IF OBJECT_ID('dbo.MOVIMIENTO_ECOPUNTOS', 'U') IS NULL
CREATE TABLE dbo.MOVIMIENTO_ECOPUNTOS (
    ID_MOVIMIENTO INT IDENTITY(1,1) PRIMARY KEY,
    ID_CUENTA INT NOT NULL REFERENCES dbo.CUENTA_ECOPUNTOS(ID_CUENTA),
    TIPO NVARCHAR(20) NOT NULL,
    PUNTOS INT NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    MOTIVO NVARCHAR(200) NULL
);
GO

IF OBJECT_ID('dbo.BENEFICIO', 'U') IS NULL
CREATE TABLE dbo.BENEFICIO (
    ID_BENEFICIO INT IDENTITY(1,1) PRIMARY KEY,
    TIPO NVARCHAR(20) NOT NULL,
    DESCRIPCION NVARCHAR(200) NOT NULL,
    PUNTOS_REQUERIDOS INT NOT NULL,
    COSTO_EMPRESA DECIMAL(10,2) NOT NULL DEFAULT 0,
    ACTIVO BIT NOT NULL DEFAULT 1
);
GO

IF OBJECT_ID('dbo.CANJE', 'U') IS NULL
CREATE TABLE dbo.CANJE (
    ID_CANJE INT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    ID_CUENTA INT NOT NULL REFERENCES dbo.CUENTA_ECOPUNTOS(ID_CUENTA),
    ID_BENEFICIO INT NOT NULL REFERENCES dbo.BENEFICIO(ID_BENEFICIO),
    PUNTOS_USADOS INT NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    ESTADO NVARCHAR(20) NOT NULL DEFAULT N'APROBADO'
);
GO

-- ---------- N01: gestión de la red de puntos verdes y tarifas ----------

IF OBJECT_ID('dbo.INFORME_GESTION', 'U') IS NULL
CREATE TABLE dbo.INFORME_GESTION (
    ID_INFORME INT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    TIPO NVARCHAR(50) NOT NULL,
    PERIODO NVARCHAR(7) NOT NULL,
    FECHA_GENERACION DATETIME NOT NULL DEFAULT GETDATE()
);
GO

IF OBJECT_ID('dbo.DECISION', 'U') IS NULL
CREATE TABLE dbo.DECISION (
    ID_DECISION INT IDENTITY(1,1) PRIMARY KEY,
    ID_INFORME INT NULL REFERENCES dbo.INFORME_GESTION(ID_INFORME),
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    ID_PUNTO_VERDE INT NULL REFERENCES dbo.PUNTO_VERDE(ID_PUNTO_VERDE),
    TIPO NVARCHAR(50) NOT NULL,
    DESCRIPCION NVARCHAR(500) NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE()
);
GO

IF OBJECT_ID('dbo.TARIFA_COMISION', 'U') IS NULL
CREATE TABLE dbo.TARIFA_COMISION (
    ID_TARIFA INT IDENTITY(1,1) PRIMARY KEY,
    ID_DECISION INT NULL REFERENCES dbo.DECISION(ID_DECISION),
    CATEGORIA NVARCHAR(50) NOT NULL,
    PORCENTAJE DECIMAL(5,2) NOT NULL,
    VIGENTE_DESDE DATE NOT NULL DEFAULT CAST(GETDATE() AS DATE)
);
GO

IF OBJECT_ID('dbo.TABLA_CONVERSION', 'U') IS NULL
CREATE TABLE dbo.TABLA_CONVERSION (
    ID_CONVERSION INT IDENTITY(1,1) PRIMARY KEY,
    ID_DECISION INT NULL REFERENCES dbo.DECISION(ID_DECISION),
    ID_MATERIAL INT NOT NULL REFERENCES dbo.MATERIAL(ID_MATERIAL),
    PUNTOS_POR_KG DECIMAL(10,2) NOT NULL,
    VIGENTE_DESDE DATE NOT NULL DEFAULT CAST(GETDATE() AS DATE)
);
GO

-- ---------- N02: venta de productos sustentables y comisión ----------

IF OBJECT_ID('dbo.VERIFICACION_VENDEDOR', 'U') IS NULL
CREATE TABLE dbo.VERIFICACION_VENDEDOR (
    ID_VERIFICACION INT IDENTITY(1,1) PRIMARY KEY,
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    ESTADO NVARCHAR(20) NOT NULL DEFAULT N'PENDIENTE',
    DOCUMENTO_REF NVARCHAR(200) NULL
);
GO

IF OBJECT_ID('dbo.PRODUCTO', 'U') IS NULL
CREATE TABLE dbo.PRODUCTO (
    ID_PRODUCTO INT IDENTITY(1,1) PRIMARY KEY,
    ID_VENDEDOR INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    ID_TARIFA INT NULL REFERENCES dbo.TARIFA_COMISION(ID_TARIFA),
    NOMBRE NVARCHAR(150) NOT NULL,
    DESCRIPCION NVARCHAR(500) NULL,
    CATEGORIA NVARCHAR(50) NOT NULL,
    PRECIO DECIMAL(10,2) NOT NULL,
    STOCK INT NOT NULL,
    ESTADO NVARCHAR(20) NOT NULL DEFAULT N'PENDIENTE'
);
GO

IF OBJECT_ID('dbo.ORDEN_VENTA', 'U') IS NULL
CREATE TABLE dbo.ORDEN_VENTA (
    ID_ORDEN INT IDENTITY(1,1) PRIMARY KEY,
    ID_COMPRADOR INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    ID_VENDEDOR INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    FECHA DATETIME NOT NULL DEFAULT GETDATE(),
    ESTADO NVARCHAR(30) NOT NULL DEFAULT N'PENDIENTE_PAGO',
    MONTO_BRUTO DECIMAL(10,2) NOT NULL,
    DIRECCION_ENVIO NVARCHAR(200) NULL
);
GO

IF OBJECT_ID('dbo.ORDEN_DETALLE', 'U') IS NULL
CREATE TABLE dbo.ORDEN_DETALLE (
    ID_ORDEN INT NOT NULL REFERENCES dbo.ORDEN_VENTA(ID_ORDEN),
    ID_PRODUCTO INT NOT NULL REFERENCES dbo.PRODUCTO(ID_PRODUCTO),
    CANTIDAD INT NOT NULL,
    PRECIO_UNITARIO DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (ID_ORDEN, ID_PRODUCTO)
);
GO

IF OBJECT_ID('dbo.PAGO', 'U') IS NULL
CREATE TABLE dbo.PAGO (
    ID_PAGO INT IDENTITY(1,1) PRIMARY KEY,
    ID_ORDEN INT NOT NULL REFERENCES dbo.ORDEN_VENTA(ID_ORDEN),
    REFERENCIA_PASARELA NVARCHAR(100) NULL,
    MONTO DECIMAL(10,2) NOT NULL,
    ESTADO NVARCHAR(20) NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE()
);
GO

IF OBJECT_ID('dbo.COMISION', 'U') IS NULL
CREATE TABLE dbo.COMISION (
    ID_COMISION INT IDENTITY(1,1) PRIMARY KEY,
    ID_ORDEN INT NOT NULL REFERENCES dbo.ORDEN_VENTA(ID_ORDEN),
    PORCENTAJE DECIMAL(5,2) NOT NULL,
    MONTO DECIMAL(10,2) NOT NULL,
    FECHA DATETIME NOT NULL DEFAULT GETDATE()
);
GO

IF OBJECT_ID('dbo.LIQUIDACION_VENDEDOR', 'U') IS NULL
CREATE TABLE dbo.LIQUIDACION_VENDEDOR (
    ID_LIQUIDACION INT IDENTITY(1,1) PRIMARY KEY,
    ID_ORDEN INT NOT NULL UNIQUE REFERENCES dbo.ORDEN_VENTA(ID_ORDEN),
    MONTO_NETO DECIMAL(10,2) NOT NULL,
    ESTADO NVARCHAR(30) NOT NULL DEFAULT N'RETENIDA',
    FECHA_DISPONIBLE DATE NULL,
    FECHA_PAGO DATE NULL
);
GO

IF OBJECT_ID('dbo.RECLAMO', 'U') IS NULL
CREATE TABLE dbo.RECLAMO (
    ID_RECLAMO INT IDENTITY(1,1) PRIMARY KEY,
    ID_ORDEN INT NOT NULL REFERENCES dbo.ORDEN_VENTA(ID_ORDEN),
    ID_USUARIO INT NOT NULL REFERENCES dbo.USUARIO(ID_USUARIO),
    MOTIVO NVARCHAR(300) NOT NULL,
    ESTADO NVARCHAR(20) NOT NULL DEFAULT N'ABIERTO',
    FECHA DATETIME NOT NULL DEFAULT GETDATE()
);
GO

