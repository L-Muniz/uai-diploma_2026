GO

CREATE OR ALTER PROCEDURE ROL_ELIMINAR
    @ID_ROL INT
AS
BEGIN
    SET NOCOUNT ON;

    DECLARE @ID_HIJO INT;
    DECLARE cur CURSOR LOCAL FAST_FORWARD FOR
        SELECT ID_ROL FROM ROL WHERE ID_ROL_PADRE = @ID_ROL;

    OPEN cur;
    FETCH NEXT FROM cur INTO @ID_HIJO;
    WHILE @@FETCH_STATUS = 0
    BEGIN
        EXEC ROL_ELIMINAR @ID_HIJO;
        FETCH NEXT FROM cur INTO @ID_HIJO;
    END
    CLOSE cur;
    DEALLOCATE cur;

    DELETE FROM USUARIO_ROL WHERE ID_ROL = @ID_ROL;
    IF OBJECT_ID('dbo.ROL_PERMISO', 'U') IS NOT NULL
        DELETE FROM ROL_PERMISO WHERE ID_ROL = @ID_ROL;
    IF OBJECT_ID('dbo.ROL_PERFIL', 'U') IS NOT NULL
        DELETE FROM ROL_PERFIL WHERE ID_ROL = @ID_ROL;
    DELETE FROM ROL WHERE ID_ROL = @ID_ROL;
END;
GO

