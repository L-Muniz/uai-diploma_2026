CREATE OR ALTER PROCEDURE ROL_LISTAR_TODOS
AS
BEGIN
    SET NOCOUNT ON;
    SELECT ID_ROL, NOMBRE, DESCRIPCION, ID_ROL_PADRE
    FROM ROL
    WHERE ACTIVO = 1 OR ACTIVO IS NULL
    ORDER BY NOMBRE;
END;
GO

