-- Ejecutar en la base Proyecto

CREATE OR ALTER PROCEDURE ROL_ACTUALIZAR
    @ID_ROL INT,
    @NOMBRE NVARCHAR(100),
    @DESCRIPCION NVARCHAR(500),
    @ID_ROL_PADRE INT = 0
AS
BEGIN
    SET NOCOUNT ON;
    UPDATE ROL
    SET NOMBRE = @NOMBRE,
        DESCRIPCION = @DESCRIPCION,
        ID_ROL_PADRE = CASE WHEN @ID_ROL_PADRE = 0 THEN NULL ELSE @ID_ROL_PADRE END
    WHERE ID_ROL = @ID_ROL;
END;
GO

CREATE OR ALTER PROCEDURE ROL_ASIGNAR_PADRE
    @ID_ROL INT,
    @ID_ROL_PADRE INT = 0
