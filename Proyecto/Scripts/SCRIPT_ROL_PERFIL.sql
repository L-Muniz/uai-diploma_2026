IF OBJECT_ID('dbo.ROL_PERFIL', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.ROL_PERFIL
    (
        ID_ROL INT NOT NULL,
        ID_PERFIL INT NOT NULL,
        CONSTRAINT PK_ROL_PERFIL PRIMARY KEY (ID_ROL, ID_PERFIL),
        CONSTRAINT FK_ROL_PERFIL_ROL FOREIGN KEY (ID_ROL) REFERENCES dbo.ROL (ID_ROL),
        CONSTRAINT FK_ROL_PERFIL_PERFIL FOREIGN KEY (ID_PERFIL) REFERENCES dbo.PERFIL (ID_PERFIL)
    );
END
GO
CREATE OR ALTER PROCEDURE dbo.ROL_AGREGAR_PERFIL
    @ID_ROL INT,
    @ID_PERFIL INT
AS
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM dbo.ROL_PERFIL
        WHERE ID_ROL = @ID_ROL AND ID_PERFIL = @ID_PERFIL)
    BEGIN
        INSERT INTO dbo.ROL_PERFIL (ID_ROL, ID_PERFIL)
        VALUES (@ID_ROL, @ID_PERFIL);
    END
END
GO
CREATE OR ALTER PROCEDURE dbo.ROL_QUITAR_PERFIL
    @ID_ROL INT,
    @ID_PERFIL INT
AS
BEGIN
    DELETE FROM dbo.ROL_PERFIL
    WHERE ID_ROL = @ID_ROL AND ID_PERFIL = @ID_PERFIL;
END
GO
CREATE OR ALTER PROCEDURE dbo.ROL_OBTENER_PERFILES
    @ID_ROL INT
AS
BEGIN
    SELECT p.ID_PERFIL, p.NOMBRE, p.DESCRIPCION, p.ID_PERFIL_PADRE
    FROM dbo.ROL_PERFIL rp
    INNER JOIN dbo.PERFIL p ON p.ID_PERFIL = rp.ID_PERFIL
    WHERE rp.ID_ROL = @ID_ROL
    ORDER BY p.NOMBRE;
END
GO
CREATE OR ALTER PROCEDURE dbo.ROL_ELIMINAR
    @ID_ROL INT
AS
BEGIN
    DECLARE @ID_HIJO INT;
    DECLARE cur CURSOR LOCAL FAST_FORWARD FOR
        SELECT ID_ROL FROM dbo.ROL WHERE ID_ROL_PADRE = @ID_ROL;
    OPEN cur;
    FETCH NEXT FROM cur INTO @ID_HIJO;
    WHILE @@FETCH_STATUS = 0
    BEGIN
        EXEC dbo.ROL_ELIMINAR @ID_HIJO;
        FETCH NEXT FROM cur INTO @ID_HIJO;
    END
    CLOSE cur;
    DEALLOCATE cur;
    DELETE FROM dbo.USUARIO_ROL WHERE ID_ROL = @ID_ROL;
    IF OBJECT_ID('dbo.ROL_PERMISO', 'U') IS NOT NULL
        DELETE FROM dbo.ROL_PERMISO WHERE ID_ROL = @ID_ROL;
    IF OBJECT_ID('dbo.ROL_PERFIL', 'U') IS NOT NULL
        DELETE FROM dbo.ROL_PERFIL WHERE ID_ROL = @ID_ROL;
    DELETE FROM dbo.ROL WHERE ID_ROL = @ID_ROL;
END
GO
CREATE OR ALTER PROCEDURE dbo.PERFIL_ELIMINAR
    @ID_PERFIL INT
AS
BEGIN
    DECLARE @ID_HIJO INT;
    DECLARE cur CURSOR LOCAL FAST_FORWARD FOR
        SELECT ID_PERFIL FROM dbo.PERFIL WHERE ID_PERFIL_PADRE = @ID_PERFIL;
    OPEN cur;
    FETCH NEXT FROM cur INTO @ID_HIJO;
    WHILE @@FETCH_STATUS = 0
    BEGIN
        EXEC dbo.PERFIL_ELIMINAR @ID_HIJO;
        FETCH NEXT FROM cur INTO @ID_HIJO;
    END
    CLOSE cur;
    DEALLOCATE cur;
    DELETE FROM dbo.PERFIL_PERMISO WHERE ID_PERFIL = @ID_PERFIL;
    IF OBJECT_ID('dbo.ROL_PERFIL', 'U') IS NOT NULL
        DELETE FROM dbo.ROL_PERFIL WHERE ID_PERFIL = @ID_PERFIL;
    DELETE FROM dbo.PERFIL WHERE ID_PERFIL = @ID_PERFIL;
END
GO
