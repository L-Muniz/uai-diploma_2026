CREATE OR ALTER PROCEDURE dbo.IDIOMA_AGREGAR
    @CODIGO NVARCHAR(10),
    @NOMBRE NVARCHAR(100)
AS
BEGIN
    INSERT INTO dbo.IDIOMA (CODIGO, NOMBRE, ACTIVO)
    VALUES (@CODIGO, @NOMBRE, 1);
END
GO

CREATE OR ALTER PROCEDURE dbo.IDIOMA_OBTENER_ID
    @CODIGO NVARCHAR(10)
AS
BEGIN
    SELECT ID_IDIOMA
    FROM dbo.IDIOMA
    WHERE CODIGO = @CODIGO;
END
GO

CREATE OR ALTER PROCEDURE dbo.SELECT_TRADUCCION
    @CLAVE NVARCHAR(200),
    @ID_IDIOMA INT
AS
BEGIN
    SELECT VALOR
    FROM dbo.TRADUCCION
    WHERE CLAVE = @CLAVE AND ID_IDIOMA = @ID_IDIOMA;
END
GO

CREATE OR ALTER PROCEDURE dbo.TRADUCCION_AGREGAR
    @CLAVE NVARCHAR(200),
    @CODIGO NVARCHAR(10),
    @VALOR NVARCHAR(MAX)
AS
BEGIN
    DECLARE @ID_IDIOMA INT;

    SELECT @ID_IDIOMA = ID_IDIOMA
    FROM dbo.IDIOMA
    WHERE CODIGO = UPPER(@CODIGO);

    IF @ID_IDIOMA IS NULL
    BEGIN
        RAISERROR('Idioma no encontrado', 16, 1);
        RETURN;
    END

    IF NOT EXISTS (
        SELECT 1 FROM dbo.TRADUCCION
        WHERE CLAVE = UPPER(@CLAVE) AND ID_IDIOMA = @ID_IDIOMA)
    BEGIN
        INSERT INTO dbo.TRADUCCION (CLAVE, ID_IDIOMA, VALOR)
        VALUES (UPPER(@CLAVE), @ID_IDIOMA, @VALOR);
    END
    ELSE
    BEGIN
        UPDATE dbo.TRADUCCION
        SET VALOR = @VALOR
        WHERE CLAVE = UPPER(@CLAVE) AND ID_IDIOMA = @ID_IDIOMA;
    END
END
GO

