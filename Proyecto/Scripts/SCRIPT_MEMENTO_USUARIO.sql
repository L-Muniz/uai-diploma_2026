-- Tabla y procedimientos para el Memento de usuario.
-- El historial no tiene FK a USUARIO: sobrevive a la eliminación del usuario.

IF OBJECT_ID('dbo.MEMENTO_USUARIO', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.MEMENTO_USUARIO (
        ID_MEMENTO INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_MEMENTO_USUARIO PRIMARY KEY,
        ID_USUARIO INT NOT NULL,
        DESCRIPCION NVARCHAR(500) NULL,
        CONTENIDO NVARCHAR(MAX) NOT NULL,   -- XML del estado, encriptado con AES (SV_Encriptacion)
        FECHA_CAPTURA DATETIME NOT NULL
    );
    CREATE INDEX IX_MEMENTO_USUARIO_ID_USUARIO ON dbo.MEMENTO_USUARIO (ID_USUARIO);
END
GO

CREATE OR ALTER PROCEDURE MEMENTO_USUARIO_ALTA
    @ID_USUARIO INT,
    @DESCRIPCION NVARCHAR(500),
    @CONTENIDO NVARCHAR(MAX),
    @FECHA_CAPTURA DATETIME
AS
BEGIN
    SET NOCOUNT ON;
    INSERT INTO MEMENTO_USUARIO (ID_USUARIO, DESCRIPCION, CONTENIDO, FECHA_CAPTURA)
    VALUES (@ID_USUARIO, @DESCRIPCION, @CONTENIDO, @FECHA_CAPTURA);
    SELECT CAST(SCOPE_IDENTITY() AS INT) AS ID_MEMENTO;
END
GO

CREATE OR ALTER PROCEDURE MEMENTO_USUARIO_LISTAR
AS
BEGIN
    SET NOCOUNT ON;
    SELECT ID_MEMENTO, ID_USUARIO, DESCRIPCION, CONTENIDO, FECHA_CAPTURA
    FROM MEMENTO_USUARIO
    ORDER BY FECHA_CAPTURA DESC;
END
GO

CREATE OR ALTER PROCEDURE MEMENTO_USUARIO_LISTAR_X_USUARIO
    @ID_USUARIO INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT ID_MEMENTO, ID_USUARIO, DESCRIPCION, CONTENIDO, FECHA_CAPTURA
    FROM MEMENTO_USUARIO
    WHERE ID_USUARIO = @ID_USUARIO
    ORDER BY FECHA_CAPTURA DESC;
END
GO

CREATE OR ALTER PROCEDURE MEMENTO_USUARIO_OBTENER
    @ID_MEMENTO INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT ID_MEMENTO, ID_USUARIO, DESCRIPCION, CONTENIDO, FECHA_CAPTURA
    FROM MEMENTO_USUARIO
    WHERE ID_MEMENTO = @ID_MEMENTO;
END
GO

CREATE OR ALTER PROCEDURE USUARIO_OBTENER_ID_ROLES
    @ID_USUARIO INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT ID_ROL FROM USUARIO_ROL WHERE ID_USUARIO = @ID_USUARIO;
END
GO

CREATE OR ALTER PROCEDURE USUARIO_QUITAR_ROL
    @ID_USUARIO INT,
    @ID_ROL INT
AS
BEGIN
    SET NOCOUNT ON;
    DELETE FROM USUARIO_ROL WHERE ID_USUARIO = @ID_USUARIO AND ID_ROL = @ID_ROL;
END
GO
