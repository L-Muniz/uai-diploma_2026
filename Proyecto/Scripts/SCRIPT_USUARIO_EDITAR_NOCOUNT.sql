IF OBJECT_ID('dbo.USUARIO_EDITAR', 'P') IS NOT NULL
    DROP PROCEDURE dbo.USUARIO_EDITAR;
GO
CREATE PROCEDURE [dbo].[USUARIO_EDITAR]
  @ID_USUARIO INT,
  @USERNAME NVARCHAR(50),
  @PASS NVARCHAR(255),
  @BLOQUEADO BIT,
  @DVH_HORIZONTAL INT
AS
BEGIN
  SET NOCOUNT OFF;
  UPDATE USUARIO
  SET USERNAME = @USERNAME,
      PASS = @PASS,
      BLOQUEADO = @BLOQUEADO,
      DVH_HORIZONTAL = @DVH_HORIZONTAL
  WHERE ID_USUARIO = @ID_USUARIO;
END
GO
